#!/usr/bin/env python3
"""Generate dense search registries or the final paged compilation units."""

from __future__ import annotations

import argparse
from dataclasses import astuple
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from helper.kernel_configs import SCENARIOS, get_configs, kernel_directory
from helper.search_space import dense_search_space, paged_search_space


def cpp_config(cfg, paged=False, causal=False) -> str:
    fields = [cfg.dtype.to_cpp_str()] + [
        str(value).lower() for value in astuple(cfg)[1:13]
    ]
    if paged:
        fields.extend(("true", str(cfg.page_size)))
    elif causal:
        fields.append("true")
    return "ForwardKernelConfig{" + ", ".join(fields) + "}"


def dense_files(directory: Path, namespace: str, causal=False) -> dict[Path, str]:
    lines = [
        "// Generated by tools/build/generate_instances.py.", "#pragma once", "#include <map>",
        '#include "kernel_traits.cuh"', '#include "forward_kernel.cuh"',
        '#include "static_kernel_configuration.cuh"', f"namespace {namespace} {{",
        "using forward_kernel_fn = void (*)(const ForwardKernelArgs);",
        "std::map<ForwardKernelConfig, forward_kernel_fn> forward_kernels = {",
    ]
    for head_dim in (128, 64):
        for cfg in dense_search_space(head_dim):
            key = cpp_config(cfg, causal=causal)
            lines.append(f"    {{{key}, &flash_attention_forward_kernel<StaticForwardKernelConfig<{key}>>}},")
    lines.extend(("};", f"}} // namespace {namespace}", ""))
    return {directory / "include/flash_kernels.cuh": "\n".join(lines)}


def paged_files(directory: Path, namespace: str) -> dict[Path, str]:
    groups = {}
    for head_dim in (128, 64):
        for cfg in paged_search_space(head_dim):
            name = (f"p{cfg.page_size}_{cfg.dtype.name.lower()}_br{cfg.Br}_bc{cfg.Bc}"
                    f"_pre{int(cfg.prefetch_kv_tiles)}")
            if head_dim == 64:
                name += "_d64"
            groups.setdefault(name, []).append(cfg)
    prefix = "// Generated by tools/build/generate_instances.py."
    files = {}
    for name, configs in groups.items():
        lines = [prefix, '#include "kernel_traits.cuh"', '#include "forward_kernel.cuh"',
                 '#include "static_kernel_configuration.cuh"', "#include <map>",
                 f"namespace {namespace} {{",
                 "using forward_kernel_fn = void (*)(const ForwardKernelArgs);",
                 f"void register_{name}(std::map<ForwardKernelConfig, forward_kernel_fn>& normal,",
                 "    std::map<ForwardKernelConfig, forward_kernel_fn>& single) {"]
        for cfg in configs:
            key = cpp_config(cfg, paged=True)
            lines.append(f"    normal.emplace({key}, &flash_attention_forward_kernel<StaticForwardKernelConfig<{key}>>);")
            if cfg.page_size > cfg.Bc:
                lines.append(f"    single.emplace({key}, &flash_attention_forward_kernel<StaticForwardKernelConfig<{key}>, true>);")
        lines.extend(("}", f"}} // namespace {namespace}", ""))
        files[directory / f"csrc/instances/{name}.cu"] = "\n".join(lines)
    lines = [prefix, "#pragma once", "#include <map>", '#include "kernel_traits.cuh"',
             f"namespace {namespace} {{", "struct ForwardKernelArgs;",
             "using forward_kernel_fn = void (*)(const ForwardKernelArgs);",
             "using KernelMap = std::map<ForwardKernelConfig, forward_kernel_fn>;"]
    lines.extend(f"void register_{name}(KernelMap&, KernelMap&);" for name in groups)
    lines.extend(("KernelMap forward_kernels;", "KernelMap single_page_kernels;",
                  "inline void register_forward_kernels() {"))
    lines.extend(f"    register_{name}(forward_kernels, single_page_kernels);" for name in groups)
    lines.extend(("}", f"}} // namespace {namespace}", ""))
    files[directory / "include/flash_kernels.cuh"] = "\n".join(lines)
    return files


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scenario", choices=SCENARIOS, required=True)
    parser.add_argument("--version", type=int, help="local step number; default: final kernel")
    parser.add_argument("--check", action="store_true", help="compare registered configurations without writing")
    args = parser.parse_args()
    directory = kernel_directory(args.scenario, args.version)
    if args.scenario == "standard" and args.version in (1, 2, 3):
        parser.error("the first three standard kernels use fixed configurations")
    is_paged = args.scenario == "paged"
    if is_paged and not (directory / "csrc/instances").is_dir():
        parser.error("paged generation requires the final page-pipeline implementation")
    if args.check:
        for head_dim in (64, 128):
            expected = paged_search_space(head_dim) if is_paged else dense_search_space(head_dim)
            actual = get_configs(args.scenario, args.version, head_dim=head_dim)
            if set(actual) != set(expected):
                raise SystemExit(f"registry differs from the configured search space: {directory}, D={head_dim}")
        print(f"Verified registered configurations: {directory}")
        return
    source = (directory / "csrc/flash_attention.cu").read_text()
    namespace = re.search(r"using namespace (flash_attn_lab::[\w:]+);", source).group(1)
    files = (paged_files(directory, namespace) if is_paged
             else dense_files(directory, namespace, causal=args.scenario == "causal"))
    obsolete = (
        set((directory / "csrc/instances").glob("p*_*.cu")) - set(files)
        if is_paged else set()
    )
    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    for path in obsolete:
        path.unlink()
    print(f"Generated {len(files)} files in {directory}")


if __name__ == "__main__":
    main()
